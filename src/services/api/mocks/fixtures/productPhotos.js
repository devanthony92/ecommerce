const slugify = (text) =>
  text.normalize('NFKD').replace(/[̀-ͯ]/g, '').toLowerCase().replaceAll(' ', '-')

export function productPhoto(slug, colorName) {
  const name = `${slug}-${slugify(colorName)}`
  return PHOTOS.has(name) ? `/images/products/${name}.webp` : null
}
