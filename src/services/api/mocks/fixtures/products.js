// PRNG determinista (mulberry32) para stock y ventas.
function seeded(seed) {
  let state = seed
  return () => {
    state = (state + 0x6d2b79f5) | 0
    let t = Math.imul(state ^ (state >>> 15), 1 | state)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const DAY = 24 * 60 * 60 * 1000
const NOW = Date.UTC(2026, 9, 1)

export const products = RAW.map(
  ([slug, name, categorySlug, shape, basePrice, colorKeys, sizeKey, tierKey, extra], index) => {
    const random = seeded(index + 1)
    const category = categories.find((c) => c.slug === categorySlug)
    const colors = colorKeys.map((key) => ({ key, ...COLORS[key] }))
    const sizes = SIZES[sizeKey]

    const variants = colors.flatMap((color) =>
      sizes.map((size) => {
        const stock = extra.outOfStock
          ? 0
          : Math.floor(random() * 6) === 0
            ? 0
            : Math.floor(random() * 150) + 5
        return {
          id: `${slug}-${color.key}-${size}`.toLowerCase(),
          sku: `${slug.slice(0, 8).toUpperCase()}-${color.key.slice(0, 3).toUpperCase()}-${size}`,
          attributes: { size, color: color.name },
          stock,
          available: stock > 0,
        }
      }),
    )

    return {
      id: `p-${slug}`,
      slug,
      name,
      categoryId: category.id,
      shape,
      basePrice,
      promoPrice: extra.promoPrice ?? null,
      tierDefs: TIERS[tierKey],
      tags: extra.tags ?? [],
      colors,
      sizes,
      variants,
      images: colors.map((color) => ({
        url: productImage(shape, color.hex),
        alt: `${name} color ${color.name.toLowerCase()}`,
        color: color.name,
        width: 400,
        height: 500,
      })),
      description: `${name} confeccionada en Colombia. Ideal para venta al detal o para surtir tu tienda con precios por volumen.`,
      createdAt: new Date(NOW - Math.floor(random() * 120) * DAY).toISOString(),
      sold: Math.floor(random() * 900),
    }
  },
)
